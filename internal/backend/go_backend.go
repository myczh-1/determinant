func writeJSON(response http.ResponseWriter, status int, value any) {
	response.Header().Set("Content-Type", "application/json")
	response.WriteHeader(status)
	if status != http.StatusNoContent && value != nil { _ = json.NewEncoder(response).Encode(value) }
}

func matchRoute(template, actual string) (map[string]string, bool) {
	clean := func(value string) []string { value = strings.Trim(value, "/"); if value == "" { return nil }; return strings.Split(value, "/") }
	templateParts, actualParts := clean(template), clean(actual)
	if len(templateParts) != len(actualParts) { return nil, false }
	parameters := map[string]string{}
	for index, part := range templateParts {
		if strings.HasPrefix(part, "{") && strings.HasSuffix(part, "}") { parameters[strings.TrimSuffix(strings.TrimPrefix(part, "{"), "}")] = actualParts[index]; continue }
		if part != actualParts[index] { return nil, false }
	}
	return parameters, true
}

func readBody(request *http.Request) (map[string]json.RawMessage, error) {
	body := map[string]json.RawMessage{}
	if request.Body == nil { return body, nil }
	if err := json.NewDecoder(request.Body).Decode(&body); err != nil { return nil, err }
	return body, nil
}

