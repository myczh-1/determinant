func moneyFromText(currency, unit string, scale int, text string) (Money, error) {
	text = strings.TrimSpace(text)
	if text == "" { return Money{}, fmt.Errorf("invalid money") }
	negative := strings.HasPrefix(text, "-")
	unsigned := text
	if negative { unsigned = strings.TrimPrefix(unsigned, "-") }
	parts := strings.Split(unsigned, ".")
	if len(parts) > 2 || parts[0] == "" || (len(parts) == 2 && len(parts[1]) > scale) { return Money{}, fmt.Errorf("invalid money") }
	fraction := ""
	if len(parts) == 2 { fraction = parts[1] }
	if len(fraction) < scale { fraction += strings.Repeat("0", scale-len(fraction)) }
	whole, err := strconv.ParseInt(parts[0], 10, 64)
	if err != nil { return Money{}, fmt.Errorf("invalid money") }
	minorFraction := int64(0)
	if fraction != "" { minorFraction, err = strconv.ParseInt(fraction, 10, 64); if err != nil { return Money{}, fmt.Errorf("invalid money") } }
	base := int64(1)
	for i := 0; i < scale; i++ { base *= 10 }
	minor := whole*base + minorFraction
	if negative { minor = -minor }
	return Money{Currency: currency, Unit: unit, Scale: scale, Minor: minor}, nil
}

func moneyLiteral(currency, unit string, scale int, text string) Money {
	value, err := moneyFromText(currency, unit, scale, text)
	if err != nil { panic(err) }
	return value
}

func moneyValue(value Money) string {
	negative := value.Minor < 0
	absolute := value.Minor
	if negative { absolute = -absolute }
	base := int64(1)
	for i := 0; i < value.Scale; i++ { base *= 10 }
	whole := absolute / base
	if value.Scale == 0 { if negative { return "-" + strconv.FormatInt(whole, 10) }; return strconv.FormatInt(whole, 10) }
	fraction := strconv.FormatInt(absolute%base, 10)
	if len(fraction) < value.Scale { fraction = strings.Repeat("0", value.Scale-len(fraction)) + fraction }
	if negative { return "-" + strconv.FormatInt(whole, 10) + "." + fraction }
	return strconv.FormatInt(whole, 10) + "." + fraction
}

func assertCompatibleMoney(left, right Money) {
	if left.Currency != right.Currency || left.Unit != right.Unit || left.Scale != right.Scale { panic("incompatible money") }
}

func moneyAdd(left, right Money) Money { assertCompatibleMoney(left, right); left.Minor += right.Minor; return left }
func moneySubtract(left, right Money) Money { assertCompatibleMoney(left, right); left.Minor -= right.Minor; return left }
func moneyMultiply(value Money, factor int64) Money { value.Minor *= factor; return value }
func moneyCompare(left, right Money) int { assertCompatibleMoney(left, right); if left.Minor < right.Minor { return -1 }; if left.Minor > right.Minor { return 1 }; return 0 }
